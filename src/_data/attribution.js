/* The Gantt axis runs from October 2025 to November 2026, one column per month. */
const AXIS_START_YEAR = 2025;
const AXIS_START_MONTH = 10;
const AXIS_MONTHS = 14;

const MONTH_LONG = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
const MONTH_SHORT = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

function parseIso(iso) {
  const parts = iso.split('-').map(Number);
  return { year: parts[0], month: parts[1], day: parts[2] };
}

function monthOffset(year, month) {
  return (year - AXIS_START_YEAR) * 12 + (month - AXIS_START_MONTH);
}

function axisPercent(iso) {
  const date = parseIso(iso);
  const daysInMonth = new Date(Date.UTC(date.year, date.month, 0)).getUTCDate();
  const withinMonth = (date.day - 1) / daysInMonth;
  return ((monthOffset(date.year, date.month) + withinMonth) / AXIS_MONTHS) * 100;
}

function longDate(iso) {
  const date = parseIso(iso);
  return MONTH_LONG[date.month - 1] + ' ' + date.day + ', ' + date.year;
}

function shortDate(iso) {
  const date = parseIso(iso);
  return MONTH_SHORT[date.month - 1] + ' ' + date.day;
}

